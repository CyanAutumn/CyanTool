using CyanTools.Utils;
using Xunit;

namespace CyanTools.PathDefaults.Tests;

public sealed class ToolOutputDirectoryDefaultsTests
{
    [Fact]
    public void BuildDefaultOutputDirectory_UsesInputParentAndToolName()
    {
        var inputPath = Path.Combine("aaa", "bbb");

        var result = ToolOutputDirectoryDefaults.BuildDefaultOutputDirectory(inputPath, "图片聚类");

        Assert.Equal(Path.GetFullPath(Path.Combine("aaa", "图片聚类")), result);
    }

    [Fact]
    public void BuildDefaultOutputDirectory_ReturnsEmpty_WhenInputIsBlank()
    {
        var result = ToolOutputDirectoryDefaults.BuildDefaultOutputDirectory("   ", "图片聚类");

        Assert.Equal(string.Empty, result);
    }

    [Fact]
    public void BuildDefaultOutputDirectory_ReturnsEmpty_WhenToolNameIsBlank()
    {
        var inputPath = Path.Combine("aaa", "bbb");

        var result = ToolOutputDirectoryDefaults.BuildDefaultOutputDirectory(inputPath, " ");

        Assert.Equal(string.Empty, result);
    }

    [Fact]
    public void BuildDefaultOutputDirectory_SanitizesToolName()
    {
        var inputPath = Path.Combine("aaa", "bbb");

        var result = ToolOutputDirectoryDefaults.BuildDefaultOutputDirectory(inputPath, "图片/聚类");

        Assert.Equal(Path.GetFullPath(Path.Combine("aaa", "图片聚类")), result);
    }

    [Fact]
    public void FillWhenEmpty_KeepsExistingOutput()
    {
        var inputPath = Path.Combine("aaa", "bbb");
        var existing = Path.Combine("custom", "output");

        var result = ToolOutputDirectoryDefaults.FillWhenEmpty(existing, inputPath, "图片聚类");

        Assert.Equal(existing, result);
    }

    [Fact]
    public void FillWhenEmpty_UsesDefault_WhenOutputIsBlank()
    {
        var inputPath = Path.Combine("aaa", "bbb");

        var result = ToolOutputDirectoryDefaults.FillWhenEmpty(string.Empty, inputPath, "图片聚类");

        Assert.Equal(Path.GetFullPath(Path.Combine("aaa", "图片聚类")), result);
    }

    [Fact]
    public void RefreshForInputChange_UpdatesAutoGeneratedOutput()
    {
        var previousInput = Path.Combine("aaa", "bbb");
        var newInput = Path.Combine("ccc", "ddd");
        var currentOutput = Path.GetFullPath(Path.Combine("aaa", "图片聚类"));

        var result = ToolOutputDirectoryDefaults.RefreshForInputChange(currentOutput, previousInput, newInput, "图片聚类");

        Assert.Equal(Path.GetFullPath(Path.Combine("ccc", "图片聚类")), result);
    }

    [Fact]
    public void RefreshForInputChange_KeepsManualOutput()
    {
        var previousInput = Path.Combine("aaa", "bbb");
        var newInput = Path.Combine("ccc", "ddd");
        var currentOutput = Path.Combine("manual", "out");

        var result = ToolOutputDirectoryDefaults.RefreshForInputChange(currentOutput, previousInput, newInput, "图片聚类");

        Assert.Equal(currentOutput, result);
    }
}
